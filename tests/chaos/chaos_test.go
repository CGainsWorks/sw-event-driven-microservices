// --- results capture --------------------------------------------------------
//
// Every scenario records what it measured. The README quotes these numbers, and the rule
// is that a number in the README must come from a script in the repository — so they are
// written to a file rather than read off a terminal and typed in.

type result struct {
	Scenario   string            `json:"scenario"`
	Property   string            `json:"property_asserted"`
	Passed     bool              `json:"passed"`
	DurationMS int64             `json:"duration_ms"`
	Measured   map[string]any    `json:"measured,omitempty"`
	Notes      string            `json:"notes,omitempty"`
	Failure    string            `json:"failure,omitempty"`
	Timings    map[string]string `json:"timings,omitempty"`
}

var (
	resultsMu sync.Mutex
	results   []result
)

func record(r result) {
	resultsMu.Lock()
	defer resultsMu.Unlock()
	results = append(results, r)
}

func TestMain(m *testing.M) {
	waitForStack()
	code := m.Run()
	writeResults()
	os.Exit(code)
}

func waitForStack() {
	deadline := time.Now().Add(90 * time.Second)
	for time.Now().Before(deadline) {
		resp, err := httpClient.Get(ordersBase + "/health/ready")
		if err == nil {
			resp.Body.Close()
			if resp.StatusCode == 200 {
				return
			}
		}
		time.Sleep(time.Second)
	}
	fmt.Fprintln(os.Stderr, "the stack is not up; run `docker compose up -d --build` first")
	os.Exit(1)
}

func writeResults() {
	resultsMu.Lock()
	defer resultsMu.Unlock()

	dir := "results"
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "creating results dir: %v\n", err)
		return
	}
	payload := map[string]any{
		"$comment": "Generated by `go test -tags=chaos ./tests/chaos/...`. Every number the " +
			"README quotes about failure behaviour comes from here. Do not edit by hand.",
		"generated_at": time.Now().UTC().Format(time.RFC3339),
		"scenarios":    results,
	}
	encoded, err := json.MarshalIndent(payload, "", "  ")
	if err != nil {
		fmt.Fprintf(os.Stderr, "encoding results: %v\n", err)
		return
	}
	path := filepath.Join(dir, "chaos-results.json")
	if err := os.WriteFile(path, append(encoded, '\n'), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "writing results: %v\n", err)
		return
	}
	fmt.Printf("\nchaos results written to %s\n", path)
}

// --- scenario 1: the broker is down -----------------------------------------

// TestBrokerDownDoesNotStopOrders is the strongest claim this system makes.
//
// Kafka is stopped entirely. Orders can still be placed AND fulfilled, because the saga
// runs over gRPC and events go to the outbox rather than to the broker. Only the customer
// notification is delayed. When the broker returns, the backlog drains on its own and the
// notification arrives — nothing is lost and nothing needs replaying by hand.
//
// This is what the transactional outbox is for. Without it, either the order would fail
// because publishing failed, or the order would succeed and the event would be lost.
func TestBrokerDownDoesNotStopOrders(t *testing.T) {
	start := time.Now()
	const sku = "SKU-CHAOS-BROKER"
	setStock(t, sku, 20)

	backlogBefore := outboxPending(t, ordersBase)

	stopService(t, "kafka")

	placed, err := placeOrder(t, "pm_ok", sku, 2)
	if err != nil {
		fail(t, start, "broker down", "orders remain available with the broker stopped", err.Error())
		t.Fatalf("placing an order with the broker down must still succeed: %v", err)
	}

	// The saga does not touch Kafka: it drives inventory and payments over gRPC. A broker
	// outage must not stop a sale.
	final := awaitTerminal(t, placed.OrderID, 90*time.Second)
	if final.State != "CONFIRMED" {
		fail(t, start, "broker down", "an order completes with the broker stopped",
			fmt.Sprintf("state=%s reason=%s", final.State, final.Reason))
		t.Fatalf("order state = %s, want CONFIRMED with the broker down", final.State)
	}

	if stock := getStock(t, sku); stock.OnHand != 18 {
		t.Errorf("on_hand = %d, want 18 — the sale must complete even with no broker", stock.OnHand)
	}

	// The events exist; they are simply waiting. A backlog that did NOT grow would mean
	// events were being dropped rather than held.
	backlogDuring := outboxPending(t, ordersBase)
	if backlogDuring <= backlogBefore {
		t.Errorf("orders outbox backlog = %d, was %d before — events are not being retained",
			backlogDuring, backlogBefore)
	}
	t.Logf("outbox backlog while the broker was down: orders=%d", backlogDuring)

	startService(t, "kafka")
	waitForService(t, ordersBase, 60*time.Second)

	drainStart := time.Now()
	eventually(t, 120*time.Second, "the orders outbox to drain",
		func() bool { return outboxPending(t, ordersBase) == 0 },
		func() string { return fmt.Sprintf("still pending: %d", outboxPending(t, ordersBase)) })
	drainTook := time.Since(drainStart)

	// The end of the chain: the notification only exists if the whole pipeline recovered.
	eventually(t, 90*time.Second, "the delayed notification to arrive",
		func() bool { return len(getNotifications(t, placed.OrderID)) == 1 },
		func() string { return fmt.Sprintf("notifications: %+v", getNotifications(t, placed.OrderID)) })

	record(result{
		Scenario: "broker down",
		Property: "orders are placed and fulfilled with Kafka stopped; the outbox retains every " +
			"event and drains unaided when the broker returns; the notification arrives late but arrives",
		Passed:     true,
		DurationMS: time.Since(start).Milliseconds(),
		Measured: map[string]any{
			"orders_confirmed_with_broker_down": 1,
			"outbox_backlog_during_outage":      backlogDuring,
			"events_lost":                       0,
		},
		Timings: map[string]string{"outbox_drain_after_recovery": drainTook.Round(10 * time.Millisecond).String()},
		Notes:   "The saga runs over gRPC, so a broker outage delays notification only.",
	})
}

// --- scenario 2: a dependency is down ---------------------------------------

// TestPaymentsDownHoldsTheSaga proves the saga waits rather than guessing.
//
// payments is stopped, so its port refuses connections — a fast, unambiguous failure. The
// saga must NOT conclude the payment failed and compensate: nothing was attempted, and
// cancelling the order would be wrong. It must hold, with the stock still reserved, until
// payments returns.
//
// The stock assertion is the one that matters. If the saga wrongly compensated, the
// reservation would be released and the order cancelled — a lost sale caused by a restart.
func TestPaymentsDownHoldsTheSaga(t *testing.T) {
	start := time.Now()
	const sku = "SKU-CHAOS-PAYMENTS"
	setStock(t, sku, 10)

	stopService(t, "payments")

	placed, err := placeOrder(t, "pm_ok", sku, 3)
	if err != nil {
		t.Fatalf("orders must accept an order while payments is down: %v", err)
	}

	// Stock is reserved by step 0, which does not need payments.
	eventually(t, 60*time.Second, "stock to be reserved before payments is reached",
		func() bool { return getStock(t, sku).Reserved == 3 },
		func() string { return fmt.Sprintf("stock: %+v", getStock(t, sku)) })

	// Hold for long enough that a saga inclined to give up would have. The step timeout is
	// 10s and the first retries are seconds apart, so 30s covers several attempts.
	deadline := time.Now().Add(30 * time.Second)
	sawUnresolved := false
	for time.Now().Before(deadline) {
		order := getOrder(t, placed.OrderID)
		if order.State == "CANCELLED" {
			fail(t, start, "payments down", "the saga holds instead of compensating",
				"the order was cancelled while payments was merely unavailable")
			t.Fatalf("order was CANCELLED while payments was down; nothing was attempted, so " +
				"compensating is wrong and loses a sale")
		}
		saga := getSaga(t, placed.OrderID)
		for _, s := range saga.Steps {
			if s.Name == "authorize_payment" && (s.State == "UNKNOWN" || s.State == "PENDING") {
				sawUnresolved = true
			}
			if s.Name == "authorize_payment" && s.State == "FAILED" {
				t.Fatalf("authorize_payment was marked FAILED while payments was unreachable; " +
					"an unreachable callee is not a decline")
			}
		}
		time.Sleep(time.Second)
	}
	if !sawUnresolved {
		t.Error("authorize_payment never entered PENDING or UNKNOWN; the saga did not reach it")
	}

	if stock := getStock(t, sku); stock.Reserved != 3 {
		t.Errorf("reserved = %d, want 3 — the hold must survive the outage", stock.Reserved)
	}

	startService(t, "payments")

	recoveryStart := time.Now()
	final := awaitTerminal(t, placed.OrderID, 180*time.Second)
	recoveryTook := time.Since(recoveryStart)

	if final.State != "CONFIRMED" {
		fail(t, start, "payments down", "the order completes once payments returns",
			fmt.Sprintf("state=%s reason=%s", final.State, final.Reason))
		t.Fatalf("order state = %s, want CONFIRMED after payments returned", final.State)
	}
	if stock := getStock(t, sku); stock.OnHand != 7 || stock.Reserved != 0 {
		t.Errorf("stock after recovery = %+v, want on_hand 7 and reserved 0", stock)
	}

	record(result{
		Scenario: "payments unavailable",
		Property: "the saga holds with stock reserved rather than compensating; an unreachable " +
			"callee is never recorded as a decline; the order completes once payments returns",
		Passed:     true,
		DurationMS: time.Since(start).Milliseconds(),
		Measured: map[string]any{
			"orders_wrongly_cancelled": 0,
			"stock_wrongly_released":   0,
			"outage_seconds":           30,
		},
		Timings: map[string]string{"recovery_to_confirmed": recoveryTook.Round(100 * time.Millisecond).String()},
	})
}

// --- scenario 3: duplicate delivery -----------------------------------------

// TestDuplicateEventDoesNotDuplicateWork republishes a real event verbatim.
//
// The outbox publishes at least once and Kafka redelivers on rebalance, so duplicates are
// not hypothetical — they are the normal case this system is built to absorb. Republishing
// the exact bytes, with the same event_id, is the strongest form of that test: the consumer
// cannot tell it apart from a genuine redelivery.
//
// Exactly one notification must exist afterwards. Two would mean a customer emailed twice.
func TestDuplicateEventDoesNotDuplicateWork(t *testing.T) {
	start := time.Now()
	const sku = "SKU-CHAOS-DUPLICATE"
	setStock(t, sku, 10)

	placed, err := placeOrder(t, "pm_ok", sku, 1)
	if err != nil {
		t.Fatalf("placing order: %v", err)
	}
	if final := awaitTerminal(t, placed.OrderID, 90*time.Second); final.State != "CONFIRMED" {
		t.Fatalf("order state = %s, want CONFIRMED", final.State)
	}
	eventually(t, 60*time.Second, "the first notification",
		func() bool { return len(getNotifications(t, placed.OrderID)) == 1 },
		func() string { return fmt.Sprintf("notifications: %+v", getNotifications(t, placed.OrderID)) })

	before := getNotifications(t, placed.OrderID)

	original := findEvent(t, "orders.v1.events", placed.OrderID, "orders.v1.OrderConfirmed")
	if original == nil {
		t.Fatal("could not find the OrderConfirmed event on the topic")
	}

	const republishes = 3
	republish(t, "orders.v1.events", original, republishes)
	t.Logf("republished OrderConfirmed %d times verbatim", republishes)

	// Long enough for every copy to be consumed. A shorter wait would let this pass
	// because nothing had been delivered yet, which is a test that proves nothing.
	time.Sleep(8 * time.Second)

	after := getNotifications(t, placed.OrderID)
	if len(after) != 1 {
		fail(t, start, "duplicate delivery", "one notification per event per channel",
			fmt.Sprintf("%d notifications exist after %d republishes", len(after), republishes))
		t.Fatalf("got %d notifications after %d duplicate deliveries, want 1: %+v",
			len(after), republishes, after)
	}
	if after[0].NotificationID != before[0].NotificationID {
		t.Error("the notification id changed, so a second record was created for one event")
	}

	record(result{
		Scenario:   "duplicate delivery",
		Property:   "an event republished verbatim N times produces exactly one notification",
		Passed:     true,
		DurationMS: time.Since(start).Milliseconds(),
		Measured: map[string]any{
			"duplicate_deliveries": republishes,
			"notifications_sent":   len(after),
			"duplicates_actioned":  0,
		},
		Notes: "Deduplicated on event_id in processed_events, backed by a unique index on " +
			"(source_event_id, channel).",
	})
}

// --- scenario 4: network partition ------------------------------------------

// TestPartitionedPaymentsIsNeverMistakenForADecline is the ambiguous-outcome test.
//
// A partition is deliberately different from a stopped service. A stopped service refuses
// connections immediately; a partitioned one accepts nothing and answers nothing, so calls
// hang and the caller learns only that it did not get a reply. It cannot tell "never
// arrived" from "arrived, answer lost".
//
// The saga must record UNKNOWN, never FAILED, and must never compensate on that basis.
// Compensating here would void an authorization that might exist, or cancel an order whose
// customer has already been charged.
func TestPartitionedPaymentsIsNeverMistakenForADecline(t *testing.T) {
	start := time.Now()
	const sku = "SKU-CHAOS-PARTITION"
	setStock(t, sku, 10)

	heal := partition(t, containerName("payments"))

	placed, err := placeOrder(t, "pm_ok", sku, 2)
	if err != nil {
		t.Fatalf("orders must accept an order during a partition: %v", err)
	}

	deadline := time.Now().Add(40 * time.Second)
	sawUnresolved := false
	for time.Now().Before(deadline) {
		order := getOrder(t, placed.OrderID)
		if order.State == "CANCELLED" {
			fail(t, start, "network partition", "an unresolved outcome never becomes a decline",
				"the order was cancelled during a partition")
			t.Fatal("order was CANCELLED during a partition; the outcome was never known, " +
				"so concluding anything is wrong")
		}
		for _, s := range getSaga(t, placed.OrderID).Steps {
			if s.Name != "authorize_payment" {
				continue
			}
			if s.State == "FAILED" {
				t.Fatalf("authorize_payment = FAILED during a partition (detail %q); "+
					"a timeout is not an outcome", s.Detail)
			}
			if s.State == "UNKNOWN" || s.State == "PENDING" {
				sawUnresolved = true
			}
		}
		time.Sleep(time.Second)
	}
	if !sawUnresolved {
		t.Error("authorize_payment never reached PENDING or UNKNOWN during the partition")
	}

	if stock := getStock(t, sku); stock.Reserved != 2 {
		t.Errorf("reserved = %d, want 2 — the hold must survive a partition", stock.Reserved)
	}

	heal()

	recoveryStart := time.Now()
	final := awaitTerminal(t, placed.OrderID, 180*time.Second)
	recoveryTook := time.Since(recoveryStart)

	if final.State != "CONFIRMED" {
		fail(t, start, "network partition", "the saga resolves and completes once the partition heals",
			fmt.Sprintf("state=%s reason=%s", final.State, final.Reason))
		t.Fatalf("order state = %s, want CONFIRMED after healing", final.State)
	}

	// Exactly one payment. If the saga had retried without a stable idempotency key, or had
	// resolved an ambiguous outcome by assuming failure and starting again, there would be
	// two — and the customer would have been charged twice.
	if final.PaymentID == "" {
		t.Error("the confirmed order carries no payment id")
	}
	if stock := getStock(t, sku); stock.OnHand != 8 || stock.Reserved != 0 {
		t.Errorf("stock after recovery = %+v, want on_hand 8 and reserved 0", stock)
	}

	record(result{
		Scenario: "network partition",
		Property: "a call that hangs is recorded UNKNOWN and resolved by asking, never assumed; " +
			"no order is cancelled and no second payment is created",
		Passed:     true,
		DurationMS: time.Since(start).Milliseconds(),
		Measured: map[string]any{
			"orders_wrongly_cancelled": 0,
			"duplicate_payments":       0,
			"partition_seconds":        40,
		},
		Timings: map[string]string{"recovery_to_confirmed": recoveryTook.Round(100 * time.Millisecond).String()},
		Notes: "A partition differs from a stopped service: connections hang rather than being " +
			"refused, which is what produces a genuinely ambiguous outcome.",
	})
}

// --- kafka helpers ----------------------------------------------------------

// findEvent scans a topic for one event by aggregate id and type.
//
// Reads the whole topic from the beginning, which is fine at test volumes and avoids
// needing to know an offset.
func findEvent(t *testing.T, topic, aggregateID, eventType string) *kafka.Message {
	t.Helper()
	// Every partition must be scanned: the message is keyed by aggregate id and could be
	// on any of them.
	for partition := 0; partition < 6; partition++ {
		r := kafka.NewReader(kafka.ReaderConfig{
			Brokers:   []string{kafkaExternal},
			Topic:     topic,
			Partition: partition,
			MinBytes:  1,
			MaxBytes:  10e6,
		})
		if err := r.SetOffset(kafka.FirstOffset); err != nil {
			r.Close()
			continue
		}
		for {
			ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
			msg, err := r.ReadMessage(ctx)
			cancel()
			if err != nil {
				break
			}
			var env struct {
				EventType   string `json:"event_type"`
				AggregateID string `json:"aggregate_id"`
			}
			if json.Unmarshal(msg.Value, &env) != nil {
				continue
			}
			if env.AggregateID == aggregateID && env.EventType == eventType {
				r.Close()
				return &msg
			}
		}
		r.Close()
	}
	return nil
}

// republish writes the exact bytes back onto the topic, n times.
func republish(t *testing.T, topic string, msg *kafka.Message, n int) {
	t.Helper()
	w := &kafka.Writer{
		Addr:         kafka.TCP(kafkaExternal),
		Balancer:     &kafka.Hash{},
		RequiredAcks: kafka.RequireAll,
		BatchSize:    1,
	}
	defer w.Close()

	for i := 0; i < n; i++ {
		ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
		err := w.WriteMessages(ctx, kafka.Message{
			Topic:   topic,
			Key:     msg.Key,
			Value:   msg.Value,
			Headers: msg.Headers,
		})
		cancel()
		if err != nil {
			t.Fatalf("republishing to %s: %v", topic, err)
		}
	}
}

func fail(t *testing.T, start time.Time, scenario, property, detail string) {
	t.Helper()
	record(result{
		Scenario:   scenario,
		Property:   property,
		Passed:     false,
		DurationMS: time.Since(start).Milliseconds(),
		Failure:    detail,
	})
}
